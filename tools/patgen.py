def stones():
    out = []
    rng = random.Random(7)

    # random ashlar: courses of 75 / 150 high, lengths from a small set, cut to a 1200 wide tile
    W, H = 1200, 600
    p = Pattern("STONE-ASHLAR", "Random ashlar in courses, 1200 x 600 repeat", (W, 0), (0, H))
    polys, y = [], 0
    for course_h in (150, 75, 150, 75, 150):
        x = rng.choice((0, 75, 150))
        start = x
        while x < start + W:
            length = min(rng.choice((225, 300, 375, 450)), start + W - x)
            polys.append(rect(x, y, x + length, y + course_h))
            x += length
        y += course_h
    unique_edges(p, polys)
    out.append(p)

    # flagstone / crazy paving: periodic Voronoi, vertices snapped to 5 mm
    W = H = 1200
    seeds = poisson_points(W, H, 260, rng)
    p = Pattern("STONE-FLAGSTONE", "Crazy paving flagstones, 1200 x 1200 repeat", (W, 0), (0, H))
    unique_edges(p, [snapped_poly(c, 5) for c in periodic_voronoi(seeds, W, H)])
    out.append(p)

    # rubble: angular stones with joints, Voronoi cells inset
    W = H = 900
    seeds = poisson_points(W, H, 150, rng)
    p = Pattern("STONE-RUBBLE", "Random rubble, angular stones with joints, 900 x 900 repeat", (W, 0), (0, H))
    for cell in periodic_voronoi(seeds, W, H):
        p.add_polyline(snapped_poly(shrink(cell, 9), 3), closed=True)
    out.append(p)

    # cobbles: rounded stones, inset Voronoi cells smoothed
    W = H = 600
    seeds = poisson_points(W, H, 85, rng)
    p = Pattern("STONE-COBBLES", "Rounded cobbles, 600 x 600 repeat", (W, 0), (0, H))
    for cell in periodic_voronoi(seeds, W, H):
        p.add_polyline(snapped_poly(chaikin(shrink(cell, 7), 2), 2), closed=True)
    out.append(p)

    # setts: courses 100 high, lengths 100..160, random course offset
    W, H = 1000, 500
    p = Pattern("STONE-SETTS", "Granite setts in courses, 100 high, 1000 x 500 repeat", (W, 0), (0, H))
    polys = []
    for row in range(5):
        x0 = rng.randrange(0, 100, 10)
        x = x0
        while x < x0 + W:
            remaining = x0 + W - x
            length = remaining if remaining <= 170 else rng.choice((100, 110, 120, 130, 140, 150, 160))
            if 0 < remaining - length < 90:
                length = remaining - 90 if remaining - 90 >= 100 else remaining
            polys.append(rect(x, row * 100, x + length, row * 100 + 100))
            x += length
    unique_edges(p, polys)
    out.append(p)

    # gravel: scattered rounded pebbles
    W = H = 400
    centres = poisson_points(W, H, 46, rng)
    p = Pattern("STONE-GRAVEL", "Loose gravel, scattered pebbles, 400 x 400 repeat", (W, 0), (0, H))
    for cx, cy in centres:
        rx = rng.uniform(9, 18)
        ry = rx * rng.uniform(0.6, 0.9)
        pts = [(x + rng.uniform(-1.5, 1.5), y + rng.uniform(-1.5, 1.5))
               for x, y in ellipse(cx, cy, rx, ry, rng.uniform(0, 180), 9)]
        p.add_polyline(snapped_poly(pts, 1), closed=True)
    out.append(p)
    return out


