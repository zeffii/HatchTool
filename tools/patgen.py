"""
patgen: build .pat hatch patterns from shapes drawn in one repeating tile.

A pattern is a lattice (two vectors a, b) plus line segments in one cell. Every segment becomes a
.pat line family that repeats it at every lattice translation:

    segment P->Q, s = Q - P, written in lattice coordinates as s = alpha*a + beta*b
    v = i*a + j*b, the primitive lattice vector along s   (lines repeat along v)
    w = k*a + l*b with i*l - j*k = 1                       (step to the next line)
    family:  angle(v), P, delta = (w.u, w.n), dashes = [|s|, -(|v| - |s|)]

Segment directions must therefore be rational in the lattice basis: organic shapes are snapped to
a grid that divides the lattice vectors.

    python3 tools/patgen.py            writes patterns/*.pat
"""

import math
import os
import random
from fractions import Fraction

import numpy as np

HEADER = """;; HatchTool pattern library: {title}
;; Generated by tools/patgen.py, edit the generator rather than this file.
;; Units are millimetres. Revit reads the ;% lines, AutoCAD treats them as comments.
;%UNITS=MM
"""

EPS = 1e-7


# --------------------------------------------------------------------------- compiler

def _ext_gcd(a, b):
    if b == 0:
        return (1 if a >= 0 else -1), 0, abs(a)
    x, y, g = _ext_gcd(b, a % b)
    return y, x - (a // b) * y, g


def _frac(x, maxden=100000):
    f = Fraction(x).limit_denominator(maxden)
    if abs(float(f) - x) > 1e-6:
        raise ValueError(f"{x} is not rational in the lattice basis (snap the shape to the grid)")
    return f


class Pattern:
    def __init__(self, name, description, a, b):
        self.name, self.description = name, description
        self.a, self.b = np.array(a, float), np.array(b, float)
        self.segments = []   # (P, Q)
        self.points = []     # dots

    # lattice coordinates of a vector
    def coords(self, v):
        m = np.column_stack([self.a, self.b])
        return np.linalg.solve(m, np.asarray(v, float))

    def add_segment(self, p, q):
        p, q = np.asarray(p, float), np.asarray(q, float)
        if np.linalg.norm(q - p) > EPS:
            self.segments.append((p, q))

    def add_polyline(self, pts, closed=False):
        pts = [np.asarray(p, float) for p in pts]
        for p, q in zip(pts, pts[1:] + (pts[:1] if closed else [])):
            self.add_segment(p, q)

    def add_dot(self, p):
        self.points.append(np.asarray(p, float))

    def family(self, p, q):
        s = q - p
        alpha, beta = (_frac(c) for c in self.coords(s))
        den = math.lcm(alpha.denominator, beta.denominator)
        pi, pj = int(alpha * den), int(beta * den)
        g = math.gcd(pi, pj)
        i, j = pi // g, pj // g
        v = i * self.a + j * self.b
        lv = float(np.linalg.norm(v))
        # k, l with i*l - j*k = 1
        x, y, _ = _ext_gcd(i, j)          # i*x + j*y = 1
        l, k = x, -y
        w = k * self.a + l * self.b
        u = v / lv
        n = np.array([-u[1], u[0]])
        ls = float(np.linalg.norm(s))
        angle = math.degrees(math.atan2(u[1], u[0]))
        dashes = [] if ls >= lv - 1e-6 else [ls, -(lv - ls)]
        return angle, p[0], p[1], float(w @ u), float(w @ n), dashes

    def dot_family(self, p):
        la = float(np.linalg.norm(self.a))
        u = self.a / la
        n = np.array([-u[1], u[0]])
        w = self.b
        return math.degrees(math.atan2(u[1], u[0])), p[0], p[1], float(w @ u), float(w @ n), [0.0, -la]

    def families(self):
        out = [self.family(p, q) for p, q in self.segments]
        out += [self.dot_family(p) for p in self.points]
        return out

    def to_pat(self):
        lines = [f"*{self.name}, {self.description}", ";%TYPE=MODEL"]
        for angle, x, y, dx, dy, dashes in self.families():
            vals = [angle, x, y, dx, dy] + list(dashes)
            lines.append(",".join(_num(v) for v in vals))
        return "\n".join(lines) + "\n"


def _num(v):
    v = 0.0 if abs(v) < 5e-9 else v
    s = f"{v:.8f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


