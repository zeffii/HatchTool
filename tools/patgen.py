def herringbone(name, desc, length, width, rot):
    # 90 degree herringbone of length x width pavers (length = 2 * width), lattice (w, w) and (-w, 3w)
    w = width
    a, b = rotate([(w, w), (-w, 3 * w)], rot)
    p = Pattern(name, desc, a, b)
    unique_edges(p, [rotate(rect(0, 0, length, w), rot), rotate(rect(length, -w, length + w, w), rot)])
    return p


