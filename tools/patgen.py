def unique_edges(pat, polygons, reach=2):
    """
    edges of a tiling made of polygons in one cell: shared edges and T-junctions are resolved so
    every boundary piece is emitted exactly once modulo the lattice.
    """
    edges = []
    for m in range(-reach, reach + 1):
        for n in range(-reach, reach + 1):
            t = m * pat.a + n * pat.b
            for poly in polygons:
                pts = [np.asarray(p, float) + t for p in poly]
                for p, q in zip(pts, pts[1:] + pts[:1]):
                    edges.append((p, q))
    # split each edge at endpoints of other edges lying on it
    allpts = np.array([e[0] for e in edges] + [e[1] for e in edges])
    pieces = set()
    for p, q in edges:
        d = q - p
        ln = np.linalg.norm(d)
        u = d / ln
        rel = allpts - p
        along = rel @ u
        off = np.abs(rel @ np.array([-u[1], u[0]]))
        cuts = np.unique(np.round(along[(off < 1e-6) & (along > 1e-6) & (along < ln - 1e-6)], 6))
        ts = [0.0] + list(cuts) + [ln]
        for t0, t1 in zip(ts, ts[1:]):
            a_, b_ = p + u * t0, p + u * t1
            key = tuple(sorted([tuple(np.round(a_, 5)), tuple(np.round(b_, 5))]))
            pieces.add(key)
    # keep one representative per lattice class: midpoint in the fundamental cell
    for a_, b_ in sorted(pieces):
        a_, b_ = np.array(a_), np.array(b_)
        c = pat.coords((a_ + b_) / 2)
        c = np.round(c, 6)
        if 0 <= c[0] < 1 and 0 <= c[1] < 1:
            pat.add_segment(a_, b_)


def rect(x0, y0, x1, y1):
    return [(x0, y0), (x1, y0), (x1, y1), (x0, y1)]


def snap(p, g):
    return (round(p[0] / g) * g, round(p[1] / g) * g)


def snapped_poly(points, g):
    out = []
    for p in points:
        s = snap(p, g)
        if not out or (abs(s[0] - out[-1][0]) > EPS or abs(s[1] - out[-1][1]) > EPS):
            out.append(s)
    if len(out) > 1 and abs(out[0][0] - out[-1][0]) < EPS and abs(out[0][1] - out[-1][1]) < EPS:
        out.pop()
    return out


def rotate(points, deg, about=(0, 0)):
    r = math.radians(deg)
    c, s = math.cos(r), math.sin(r)
    return [(about[0] + (x - about[0]) * c - (y - about[1]) * s,
             about[1] + (x - about[0]) * s + (y - about[1]) * c) for x, y in points]


def chaikin(points, rounds=2):
    pts = list(points)
    for _ in range(rounds):
        new = []
        for p, q in zip(pts, pts[1:] + pts[:1]):
            new.append((0.75 * p[0] + 0.25 * q[0], 0.75 * p[1] + 0.25 * q[1]))
            new.append((0.25 * p[0] + 0.75 * q[0], 0.25 * p[1] + 0.75 * q[1]))
        pts = new
    return pts


def shrink(poly, d):
    """inset a convex polygon by d (intersection of offset half planes)"""
    pts = np.array(poly, float)
    if signed_area(pts) < 0:
        pts = pts[::-1]
    lines = []
    for p, q in zip(pts, np.roll(pts, -1, axis=0)):
        e = q - p
        nrm = np.array([-e[1], e[0]]) / np.linalg.norm(e)
        lines.append((p + nrm * d, e))
    out = []
    for (p1, e1), (p2, e2) in zip(lines, lines[1:] + lines[:1]):
        den = e1[0] * e2[1] - e1[1] * e2[0]
        if abs(den) < 1e-12:
            continue
        t = ((p2 - p1)[0] * e2[1] - (p2 - p1)[1] * e2[0]) / den
        out.append(tuple(p1 + e1 * t))
    return out


def signed_area(pts):
    pts = np.asarray(pts, float)
    x, y = pts[:, 0], pts[:, 1]
    return 0.5 * float(np.sum(x * np.roll(y, -1) - np.roll(x, -1) * y))


def periodic_voronoi(seeds, w, h):
    """Voronoi cells of seeds on a w x h torus, returned around the original seeds"""
    from scipy.spatial import Voronoi
    pts = []
    for m in (-1, 0, 1):
        for n in (-1, 0, 1):
            pts += [(x + m * w, y + n * h) for x, y in seeds]
    vor = Voronoi(np.array(pts))
    cells = []
    centre = 4 * len(seeds)  # copies with m = 0, n = 0
    for idx in range(centre, centre + len(seeds)):
        region = vor.regions[vor.point_region[idx]]
        cells.append([tuple(vor.vertices[v]) for v in region])
    return cells


def poisson_points(w, h, r, rng, tries=3000, start=None):
    """dart throwing on a torus, min distance r"""
    pts = list(start or [])
    for _ in range(tries):
        p = (rng.uniform(0, w), rng.uniform(0, h))
        ok = True
        for q in pts:
            dx = min(abs(p[0] - q[0]), w - abs(p[0] - q[0]))
            dy = min(abs(p[1] - q[1]), h - abs(p[1] - q[1]))
            if dx * dx + dy * dy < r * r:
                ok = False
                break
        if ok:
            pts.append(p)
    return pts


def ellipse(cx, cy, rx, ry, rot, n):
    pts = [(rx * math.cos(2 * math.pi * k / n), ry * math.sin(2 * math.pi * k / n)) for k in range(n)]
    return [(cx + x, cy + y) for x, y in rotate(pts, rot)]


